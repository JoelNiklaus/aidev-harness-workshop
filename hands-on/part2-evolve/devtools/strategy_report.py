"""Strategy-comparison numbers: every real strategy run in the given batch folders, the strategy ranking, spend.

    uv run python devtools/strategy_report.py --phase 4 --setup "<one paragraph>" --out "<talk>/evolve/p4-numbers.md" runs/p4/loops
    (Phase 3: --phase 3 --skip-batch loops runs/p3/loops runs/p3/loops2)

One row per run folder with a held-out result: strategy, iterations, kept patch titles, validation curve, the run's
own held-out gain with its 95% task-bootstrap CI, wall time, HF spend. Then `ranking.rank` by preset (the room's
view) with the official minimum of 5 runs and, for these small samples, with 3. Everything is read from the run folders.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from aidev_evolve import cli, ranking


def rows(dirs: list[Path]) -> list[dict]:
    out = []
    for base in dirs:
        for d in sorted(p for p in base.iterdir() if (p / "state.json").exists()):
            st = json.loads((d / "state.json").read_text())
            cfg = json.loads((d / "config.json").read_text())
            tr = (d / "transcript.jsonl").read_text().splitlines()
            wall = json.loads(tr[-1])["t"] if tr else 0.0
            out.append({"batch": base.name, "run": d.name, "dir": d, "strategy": cfg["strategy"]["name"], "state": st, "wall_min": wall / 60})
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--phase", default="3")
    ap.add_argument("--setup", default="", help="the paragraph under the title: seed, splits, proposer, time box")
    ap.add_argument("--skip-batch", action="append", default=[], help="batch folder names left out of the ranking")
    ap.add_argument("batches", nargs="+")
    a = ap.parse_args(argv)
    rs = rows([Path(b) for b in a.batches])
    pct = lambda x: f"{100 * x:.0f}%"  # noqa: E731
    pts = lambda x: f"{100 * x:+.0f}"  # noqa: E731
    L = [f"# Phase {a.phase} numbers (generated by devtools/strategy_report.py; do not edit)", "", a.setup, "",
         "| Batch | Run | Strategy | Iterations | Kept | Validation seed -> final | Held-out seed -> final | Gain [95% CI, tasks] | Wall | HF $ |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    total = 0.0
    for r in rs:
        st, ho = r["state"], r["state"].get("heldout")
        total += st["spend_usd"]
        kept = "; ".join(h["title"] for h in st["history"] if h["verdict"] == "kept") or "-"
        curve = st["curve"]
        held = f"{pct(ho['seed'])} -> {pct(ho['best'])}" if ho else "(running)"
        gain = f"{pts(ho['diff'])} [{pts(ho['ci_low'])}, {pts(ho['ci_high'])}]" if ho else "-"
        L.append(f"| {r['batch']} | {r['run']} | {r['strategy']} | {len(st['history'])} | {kept} | {pct(curve[0])} -> {pct(curve[-1])} | {held} | {gain} | "
                 f"{r['wall_min']:.0f} min | {st['spend_usd']:.2f} |")
    L += ["", f"HF spend of these runs: ${total:.2f}.", ""]
    done = [cli.run_entry(r["dir"]) for r in rs if r["state"].get("heldout") and r["batch"] not in a.skip_batch]
    ranked = sorted({r["batch"] for r in rs} - set(a.skip_batch))
    for min_runs in (ranking.MIN_RUNS, 3):
        res = ranking.rank(done, by="name", min_runs=min_runs)
        L += [f"## Strategy ranking, batch {', '.join(ranked)}, minimum {min_runs} runs", "", "```", ranking.format_table(res), "```", ""]
    Path(a.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
