"""How many held-out trials and runs separate two optimization strategies? (numbers for DESIGN.md and the talk)

    uv run --with numpy python devtools/strategy_noise.py --sweep runs/p3/sweep-C-1.jsonl runs/p3/sweep-C-2.jsonl \
        --splits runs/p3/splits/C.json --out "<talk>/evolve/strategy-noise.md"

Model: per-task true pass rates from the seed-C sweep (4 trials per task): seed C, seed C with one fix (step limit
lifted: what iteration 1 finds) and the hand-fixed reference (both fixes). A run of a strategy ends at one of these
harnesses with the strategy's probabilities (the run-to-run randomness of a strategy is which fixes its proposer
finds); each held-out task is then measured k times for the seed and the final. We simulate the room's analysis
(ranking.py): (a) one run's paired gain with a task-bootstrap CI, (b) two strategies with M runs each, CI of the
difference of their mean final score resampling runs (tasks fixed: the room's held-out set) or runs and tasks.
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np

from aidev_evolve import ranking


def rates(paths: list[str]) -> dict[str, dict[str, float]]:
    pt: dict[str, dict[str, list[int]]] = defaultdict(lambda: defaultdict(list))
    for p in paths:
        for line in Path(p).read_text().splitlines():
            if line.strip():
                r = json.loads(line)
                if r["outcome"] != "infra":
                    pt[r["candidate"]][r["task"]].append(r["outcome"] == "pass")
    return {c: {t: sum(v) / len(v) for t, v in ts.items()} for c, ts in pt.items()}


def ci(x: np.ndarray) -> tuple[float, float]:
    return float(np.quantile(x, 0.025)), float(np.quantile(x, 0.975))


def per_run(P, tasks, final, k, sims, rng, resample_pool=None):
    hw, sep = [], 0
    for _ in range(sims):
        idx = tasks if resample_pool is None else rng.choice(resample_pool, len(tasks), replace=False)
        d = rng.binomial(k, P[final][idx]) / k - rng.binomial(k, P["seed"][idx]) / k
        b = d[rng.integers(0, len(d), (1000, len(d)))].mean(1)
        lo, hi = ci(b)
        hw.append((hi - lo) / 2)
        sep += lo > 0
    return 100 * float(np.median(hw)), sep / sims


def strategies(P, tasks, mix_a, mix_b, M, k, sims, rng, with_tasks):
    names = list(P)
    hw, sep = [], 0
    for _ in range(sims):
        def runs(mix):
            hs = rng.choice(names, M, p=[mix.get(n, 0) for n in names])
            return np.array([rng.binomial(k, P[h][tasks]) / k for h in hs])
        A, B = runs(mix_a), runs(mix_b)
        n = len(tasks)
        ra, rb = rng.integers(0, M, (600, M)), rng.integers(0, M, (600, M))
        if with_tasks:
            ti = rng.integers(0, n, (600, n))
            g = np.array([A[ra[i]][:, ti[i]].mean() - B[rb[i]][:, ti[i]].mean() for i in range(600)])
            lo, hi = ci(g)
        else:  # the room's tie rule (ranking.welch): Welch t interval over run scores
            lo, hi = ranking.welch(list(A.mean(1)), list(B.mean(1)))
        hw.append((hi - lo) / 2)
        sep += (lo > 0) or (hi < 0)
    return 100 * float(np.median(hw)), sep / sims


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sweep", nargs="+", required=True)
    ap.add_argument("--splits", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--sims", type=int, default=300)
    a = ap.parse_args(argv)
    r = rates(a.sweep)
    held = json.loads(Path(a.splits).read_text())["heldout"]
    pool = sorted(r["seedC"])
    order = {t: i for i, t in enumerate(pool)}
    P = {"seed": np.array([r["seedC"][t] for t in pool]), "one": np.array([r["stepsfixed"][t] for t in pool]),
         "both": np.array([r["reference"][t] for t in pool])}
    tasks = np.array([order[t] for t in held])
    rng = np.random.default_rng(0)
    g1 = 100 * (P["one"][tasks] - P["seed"][tasks]).mean()
    g2 = 100 * (P["both"][tasks] - P["seed"][tasks]).mean()
    L = ["# Strategy ranking: noise math (generated by devtools/strategy_noise.py; do not edit)", "",
         f"Data: seed-C sweep, 34 pool tasks x 4 trials per harness. Held-out set: the {len(held)} pool tasks the loop never sees "
         f"(splits C). On it, one fix (step limit) gains {g1:+.1f} pts over seed C, both fixes (reference) {g2:+.1f} pts, so two "
         f"strategies that differ in whether their runs find the second fix differ by about {g2 - g1:.0f} pts.", "",
         "## 1. One attendee's held-out gain (final with one fix vs seed), 95% CI over tasks", "",
         "| held-out tasks | trials each | CI half-width | share of runs whose CI excludes 0 |", "|---|---|---|---|"]
    for n_t, label in ((8, "8 (random subset)"), (len(held), f"{len(held)} (all unseen)")):
        for k in (1, 2, 4):
            sub = tasks if n_t == len(held) else None
            hw, sep = per_run(P, tasks[:n_t] if sub is None else sub, "one", k, a.sims, rng, resample_pool=None if sub is not None else tasks)
            L.append(f"| {label} | {k} | ±{hw:.0f} pts | {100 * sep:.0f}% |")
    L += ["", "Reading: a single run's gain of about 20 pts comes with a ±15-20 pt interval even on all unseen tasks. "
          "Individual runs cannot be ranked against each other; the room ranks strategies, pooling runs.", "",
          "## 2. Two strategies, M runs each, 23 held-out tasks", "",
          "Scenarios (what the final harness of each run is):", "",
          "- **null**: both strategies always end with one fix (gap 0): the share separated is the false-winner rate.",
          f"- **gap {g2 - g1:.0f}**: strategy A's runs find both fixes, B's runs only the first.",
          f"- **gap {(g2 - g1) / 2:.0f}**: A always finds both, B in half of its runs.", "",
          "| scenario | runs per strategy | trials | CI half-width (runs, Welch) | separated | CI half-width (runs + tasks resampled) | separated |",
          "|---|---|---|---|---|---|---|"]
    scen = [("null", {"one": 1}, {"one": 1}), (f"gap {g2 - g1:.0f}", {"both": 1}, {"one": 1}),
            (f"gap {(g2 - g1) / 2:.0f}", {"both": 1}, {"both": 0.5, "one": 0.5})]
    for name, ma, mb in scen:
        for M in (3, 5, 10, 20):
            for k in (1, 2):
                h1, s1 = strategies(P, tasks, ma, mb, M, k, a.sims // 2, rng, False)
                h2, s2 = strategies(P, tasks, ma, mb, M, k, a.sims // 2, rng, True)
                L.append(f"| {name} | {M} | {k} | ±{h1:.1f} | {100 * s1:.0f}% | ±{h2:.1f} | {100 * s2:.0f}% |")
    L += ["", "Reading: with the room's tie rule (Welch t interval over runs, tasks fixed) the false-winner rate stays near 5%, "
          "and 5 runs per strategy already separate the 8-point gap most of the time; ranking.py does not rank strategies "
          "with fewer than 5 runs. A 4-point gap needs about 20 runs per strategy. Resampling "
          "tasks as well (would the gain hold on other tasks like these?) needs far more runs for the same power; it is shown as a "
          "second interval, not used for ties."]
    Path(a.out).write_text("\n".join(L) + "\n")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
